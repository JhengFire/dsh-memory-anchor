/**
 * 实测数据：不同向量源的分数分布，用于分别设定阈值。
 *
 * 记录于 2026-11-23，火山 doubao-embedding-vision-251215。
 * 这不是推测，是跑出来的数字，用于论证阈值取值。
 *
 * | 来源     | 正例 min | 负例 max | 间隔   | 建议阈值 |
 * |----------|----------|----------|--------|----------|
 * | hash-512 | ~0.08    | ~0.18    | 负向   | 0.15     |
 * | remote-1024 | 0.517 | 0.299   | 0.218  | 0.50     |
 * | remote-2048 | 0.657 | 0.489    | 0.168  | 0.55     |
 *
 * 关键观察：
 *   1. 1024 维的区分度优于 2048 维，且存储减半 —— 默认用 1024。
 *   2. 跨语言在 remote 下最低 0.517，**低于 0.55 阈值会被挡掉**。
 *      实测：英文查中文记忆 0.517~0.530，用 0.55 时这三类查询全部漏召回。
 *   3. 负例（无关查询）最高只到 0.299，与正例之间有 0.218 的空隙，
 *      0.50 落在空隙中间，既保住跨语言召回又不放进无关内容。
 *   4. 两个来源的分数区间几乎不重叠，因此阈值必须按 model 分别取，
 *      用同一个阈值会要么漏召回、要么放进无关内容。
 *
 * 这些数字由 bench/threshold-panel.mjs 在真实存储上跑出，改动阈值请重跑。
 */

/** 按模型给出相关性下限。 */
export const FLOOR_BY_MODEL = {
  'hash-512': 0.15,
  'remote-1024': 0.50,
  'remote-2048': 0.55,
}

/** 缺省阈值，用于未登记的模型。 */
export const DEFAULT_FLOOR = 0.3

/**
 * 取某个模型的相关性下限。
 * @param {string} model
 * @returns {number}
 */
export function floorFor(model) {
  return FLOOR_BY_MODEL[model] ?? DEFAULT_FLOOR
}