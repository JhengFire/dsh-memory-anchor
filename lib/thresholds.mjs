/**
 * 实测数据：不同向量源的分数分布，用于分别设定阈值。
 *
 * 记录于 2026-11-23，火山 doubao-embedding-vision-251215。
 * 这不是推测，是跑出来的数字，用于论证阈值取值。
 *
 * | 来源     | 正例 min | 负例 max | 间隔   | 建议阈值 |
 * |----------|----------|----------|--------|----------|
 * | hash-512 | ~0.08    | ~0.18    | 负向   | 0.15     |
 * | remote-1024 | 0.673 | 0.461    | 0.212  | 0.55     |
 * | remote-2048 | 0.657 | 0.489    | 0.168  | 0.55     |
 *
 * 关键观察：
 *   1. 1024 维的区分度优于 2048 维，且存储减半 —— 默认用 1024。
 *   2. 跨语言在 remote 下最低 0.593，高于阈值 —— 跨语言检索可用。
 *   3. 两个来源的分数区间几乎不重叠（hash 全在 0.6 以下，
 *      remote 正例在 0.65 以上）。因此阈值必须按 model 分别取，
 *      用同一个阈值会要么漏召回、要么放进无关内容。
 */

/** 按模型给出相关性下限。 */
export const FLOOR_BY_MODEL = {
  'hash-512': 0.15,
  'remote-1024': 0.55,
  'remote-2048': 0.55,
}

/** 缺省阈值，用于未登记的模型。 */
export const DEFAULT_FLOOR = 0.3

/**
 * 取某个模型的相关性下限。
 * @param {string} model
 * @returns {number}
 */
export function floorFor(model) {
  return FLOOR_BY_MODEL[model] ?? DEFAULT_FLOOR
}